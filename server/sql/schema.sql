-- ParkSpotter · modelo de datos (PostgreSQL: Supabase en la nube, PGlite en local y en las pruebas)
-- Basado en el modelo 3FN del documento (Figura 2). Los cambios respecto al documento
-- están listados en el README ("Cambios respecto al modelo del documento").
-- Todas las sentencias son idempotentes (IF NOT EXISTS) para poder ejecutarse al arrancar.
-- Se ejecuta con search_path = el esquema propio de la app (por defecto «parkspotter», ver db.js),
-- así no se mezcla con ninguna otra tabla del proyecto de Supabase.

-- Marca de tiempo ISO 8601 en UTC, igual a la que genera el servidor con toISOString().
CREATE OR REPLACE FUNCTION ahora_iso() RETURNS text
LANGUAGE sql STABLE AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;

CREATE TABLE IF NOT EXISTS usuario (
  id_usuario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         TEXT NOT NULL,
  apellido       TEXT NOT NULL,
  correo         TEXT NOT NULL,
  contrasena     TEXT NOT NULL,                       -- hash bcrypt; '!supabase' si la clave vive en Supabase Auth
  telefono       TEXT,
  tipo_usuario   TEXT NOT NULL CHECK (tipo_usuario IN ('conductor', 'propietario', 'admin')),
  fecha_registro TEXT NOT NULL DEFAULT ahora_iso(),
  estado         TEXT NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
  -- Datos personales y de perfil
  foto             TEXT,                                  -- nombre del archivo en server/data/uploads
  fecha_nacimiento TEXT,                                  -- AAAA-MM-DD; solo mayores de edad
  vehiculo_tipo    TEXT CHECK (vehiculo_tipo IN ('carro', 'moto')),
  vehiculo_placa   TEXT,
  vehiculo_detalle TEXT,                                  -- marca, modelo, color
  acepto_terminos  TEXT,                                  -- fecha en que aceptó términos y habeas data
  auth_id          UUID,                                  -- id del usuario en Supabase Auth (null = clave local)
  correo_verificado BOOLEAN NOT NULL DEFAULT TRUE         -- false hasta que confirme el código enviado a su correo
);
-- Las bases creadas antes de existir la verificación reciben la columna aquí (todas las cuentas previas cuentan como verificadas).
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS correo_verificado BOOLEAN NOT NULL DEFAULT TRUE;
-- El correo no distingue mayúsculas (equivale al COLLATE NOCASE que tenía SQLite).
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuario_correo ON usuario (lower(correo));
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuario_auth ON usuario (auth_id) WHERE auth_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS propietario (
  id_propietario   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario       INTEGER NOT NULL UNIQUE REFERENCES usuario (id_usuario),
  tipo_documento   TEXT NOT NULL CHECK (tipo_documento IN ('CC', 'CE', 'NIT', 'PASAPORTE')),
  numero_documento TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS garaje (
  id_garaje           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_propietario      INTEGER NOT NULL REFERENCES propietario (id_propietario),
  nombre              TEXT NOT NULL,
  direccion           TEXT NOT NULL,
  barrio              TEXT,
  localidad           TEXT,
  latitud             DOUBLE PRECISION NOT NULL CHECK (latitud BETWEEN -90 AND 90),
  longitud            DOUBLE PRECISION NOT NULL CHECK (longitud BETWEEN -180 AND 180),
  tarifa_hora         INTEGER NOT NULL CHECK (tarifa_hora > 0),   -- pesos colombianos (COP) por hora
  capacidad_total     INTEGER NOT NULL DEFAULT 1 CHECK (capacidad_total >= 1),
  tipo_vehiculo       TEXT NOT NULL DEFAULT 'ambos' CHECK (tipo_vehiculo IN ('carro', 'moto', 'ambos')),
  descripcion         TEXT,
  instrucciones_acceso TEXT,                                      -- solo visible con reserva confirmada
  estado              TEXT NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo', 'suspendido')),
  fecha_creacion      TEXT NOT NULL DEFAULT ahora_iso(),
  servicios           TEXT                                        -- lista separada por comas (ver lib/servicios.js)
);

-- Ventanas semanales en las que el propietario ofrece el garaje (hora local de Bogotá).
CREATE TABLE IF NOT EXISTS disponibilidad (
  id_disponibilidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_garaje         INTEGER NOT NULL REFERENCES garaje (id_garaje) ON DELETE CASCADE,
  dia_semana        INTEGER NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),  -- 1 = lunes ... 7 = domingo
  hora_inicio       TEXT NOT NULL CHECK (hora_inicio ~ '^[0-2][0-9]:[0-5][0-9]$'),
  hora_fin          TEXT NOT NULL CHECK (hora_fin ~ '^[0-2][0-9]:[0-5][0-9]$'),
  estado            TEXT NOT NULL DEFAULT 'disponible' CHECK (estado IN ('disponible', 'no_disponible')),
  CHECK (hora_inicio < hora_fin)
);

-- fecha_inicio / fecha_fin se guardan en UTC (ISO 8601); la hora local de Bogotá (UTC-5) se deriva al leer.
CREATE TABLE IF NOT EXISTS reserva (
  id_reserva      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario      INTEGER NOT NULL REFERENCES usuario (id_usuario),
  id_garaje       INTEGER NOT NULL REFERENCES garaje (id_garaje),
  fecha_inicio    TEXT NOT NULL,
  fecha_fin       TEXT NOT NULL,
  estado          TEXT NOT NULL DEFAULT 'pendiente'
                  CHECK (estado IN ('pendiente', 'confirmada', 'rechazada', 'cancelada')),
  fecha_solicitud TEXT NOT NULL DEFAULT ahora_iso(),
  costo_total     INTEGER NOT NULL CHECK (costo_total >= 0),
  tipo_vehiculo   TEXT NOT NULL CHECK (tipo_vehiculo IN ('carro', 'moto')),
  placa           TEXT NOT NULL,
  motivo          TEXT,                                           -- motivo de rechazo o cancelación
  codigo          TEXT NOT NULL DEFAULT upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6)),
                                                                  -- lo muestra el conductor; el propietario lo digita al llegar
  llegada         TEXT,                                           -- cuándo el propietario registró la llegada
  CHECK (fecha_inicio < fecha_fin)
);

-- Pago SIMULADO: no se procesa dinero real ni se guardan datos de tarjetas.
CREATE TABLE IF NOT EXISTS pago (
  id_pago     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva  INTEGER NOT NULL UNIQUE REFERENCES reserva (id_reserva),
  metodo_pago TEXT NOT NULL CHECK (metodo_pago IN ('tarjeta', 'pse', 'efectivo')),
  monto       INTEGER NOT NULL CHECK (monto >= 0),
  estado_pago TEXT NOT NULL DEFAULT 'pendiente'
              CHECK (estado_pago IN ('pendiente', 'aprobado', 'rechazado', 'reembolsado')),
  fecha_pago  TEXT,
  referencia  TEXT
);

CREATE TABLE IF NOT EXISTS calificacion (
  id_calificacion    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva         INTEGER NOT NULL UNIQUE REFERENCES reserva (id_reserva),  -- una calificación por reserva
  id_usuario         INTEGER NOT NULL REFERENCES usuario (id_usuario),
  id_garaje          INTEGER NOT NULL REFERENCES garaje (id_garaje),
  puntuacion         INTEGER NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
  comentario         TEXT,
  fecha_calificacion TEXT NOT NULL DEFAULT ahora_iso(),
  respuesta          TEXT,                                -- respuesta pública del propietario
  respuesta_fecha    TEXT
);

-- Avisos dentro de la app (solicitud nueva, reserva confirmada, etc.).
CREATE TABLE IF NOT EXISTS notificacion (
  id_notificacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario      INTEGER NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  id_reserva      INTEGER REFERENCES reserva (id_reserva) ON DELETE SET NULL,
  tipo            TEXT NOT NULL,
  mensaje         TEXT NOT NULL,
  leida           INTEGER NOT NULL DEFAULT 0 CHECK (leida IN (0, 1)),
  fecha           TEXT NOT NULL DEFAULT ahora_iso()
);

-- Fotos de cada garaje (la de menor `orden` es la principal). El archivo vive en server/data/uploads.
CREATE TABLE IF NOT EXISTS garaje_foto (
  id_foto   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_garaje INTEGER NOT NULL REFERENCES garaje (id_garaje) ON DELETE CASCADE,
  archivo   TEXT NOT NULL,
  orden     INTEGER NOT NULL DEFAULT 0,
  fecha     TEXT NOT NULL DEFAULT ahora_iso()
);

-- Chat entre conductor y propietario, dentro de una reserva.
CREATE TABLE IF NOT EXISTS mensaje (
  id_mensaje INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva INTEGER NOT NULL REFERENCES reserva (id_reserva) ON DELETE CASCADE,
  id_usuario INTEGER NOT NULL REFERENCES usuario (id_usuario),   -- quien lo escribió
  texto      TEXT NOT NULL,
  leido      INTEGER NOT NULL DEFAULT 0 CHECK (leido IN (0, 1)),
  fecha      TEXT NOT NULL DEFAULT ahora_iso()
);

-- Días en que el propietario no recibe reservas (vacaciones, arreglos…).
CREATE TABLE IF NOT EXISTS bloqueo (
  id_bloqueo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_garaje  INTEGER NOT NULL REFERENCES garaje (id_garaje) ON DELETE CASCADE,
  fecha      TEXT NOT NULL,                                -- AAAA-MM-DD (día de Bogotá)
  motivo     TEXT,
  UNIQUE (id_garaje, fecha)
);

-- Reportes de usuarios sobre una publicación; los revisa un administrador.
CREATE TABLE IF NOT EXISTS reporte (
  id_reporte INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_garaje  INTEGER NOT NULL REFERENCES garaje (id_garaje) ON DELETE CASCADE,
  id_usuario INTEGER NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  motivo     TEXT NOT NULL CHECK (motivo IN ('informacion_falsa', 'no_existe', 'inseguro', 'cobro', 'otro')),
  detalle    TEXT,
  estado     TEXT NOT NULL DEFAULT 'abierto' CHECK (estado IN ('abierto', 'resuelto')),
  fecha      TEXT NOT NULL DEFAULT ahora_iso()
);

-- Garajes guardados por cada usuario.
CREATE TABLE IF NOT EXISTS favorito (
  id_usuario INTEGER NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  id_garaje  INTEGER NOT NULL REFERENCES garaje (id_garaje) ON DELETE CASCADE,
  fecha      TEXT NOT NULL DEFAULT ahora_iso(),
  PRIMARY KEY (id_usuario, id_garaje)
);

-- Códigos de un solo uso enviados por correo (verificar la cuenta o restablecer la contraseña).
-- Solo se guarda un hash; vencen a los 15 min y se anulan tras 5 intentos fallidos.
CREATE TABLE IF NOT EXISTS codigo_correo (
  id_codigo  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
  proposito  TEXT NOT NULL CHECK (proposito IN ('verificar', 'restablecer')),
  hash       TEXT NOT NULL,
  expira     TEXT NOT NULL,
  intentos   INTEGER NOT NULL DEFAULT 0,
  creado     TEXT NOT NULL DEFAULT ahora_iso(),
  UNIQUE (id_usuario, proposito)
);

CREATE INDEX IF NOT EXISTS idx_foto_garaje          ON garaje_foto (id_garaje, orden);
CREATE INDEX IF NOT EXISTS idx_mensaje_reserva      ON mensaje (id_reserva, id_mensaje);
CREATE INDEX IF NOT EXISTS idx_garaje_propietario   ON garaje (id_propietario);
CREATE INDEX IF NOT EXISTS idx_garaje_estado        ON garaje (estado);
CREATE INDEX IF NOT EXISTS idx_disp_garaje          ON disponibilidad (id_garaje, dia_semana);
CREATE INDEX IF NOT EXISTS idx_reserva_garaje_rango ON reserva (id_garaje, estado, fecha_inicio, fecha_fin);
CREATE INDEX IF NOT EXISTS idx_reserva_usuario      ON reserva (id_usuario, fecha_inicio);
CREATE INDEX IF NOT EXISTS idx_calif_garaje         ON calificacion (id_garaje);
CREATE INDEX IF NOT EXISTS idx_notif_usuario        ON notificacion (id_usuario, leida, fecha);
CREATE INDEX IF NOT EXISTS idx_reserva_garaje_fk    ON reserva (id_garaje);
CREATE INDEX IF NOT EXISTS idx_mensaje_usuario      ON mensaje (id_usuario, fecha);

-- Seguridad en profundidad: el servidor se conecta con el rol dueño de las tablas (que ignora RLS),
-- pero si alguien llegara a exponer este esquema por la API de Supabase con la clave pública,
-- con RLS activo y sin políticas no vería ni una fila.
ALTER TABLE usuario        ENABLE ROW LEVEL SECURITY;
ALTER TABLE propietario    ENABLE ROW LEVEL SECURITY;
ALTER TABLE garaje         ENABLE ROW LEVEL SECURITY;
ALTER TABLE disponibilidad ENABLE ROW LEVEL SECURITY;
ALTER TABLE reserva        ENABLE ROW LEVEL SECURITY;
ALTER TABLE pago           ENABLE ROW LEVEL SECURITY;
ALTER TABLE calificacion   ENABLE ROW LEVEL SECURITY;
ALTER TABLE notificacion   ENABLE ROW LEVEL SECURITY;
ALTER TABLE garaje_foto    ENABLE ROW LEVEL SECURITY;
ALTER TABLE mensaje        ENABLE ROW LEVEL SECURITY;
ALTER TABLE bloqueo        ENABLE ROW LEVEL SECURITY;
ALTER TABLE reporte        ENABLE ROW LEVEL SECURITY;
ALTER TABLE favorito       ENABLE ROW LEVEL SECURITY;
ALTER TABLE codigo_correo  ENABLE ROW LEVEL SECURITY;

-- En Supabase existen los roles anon y authenticated (los de la API pública): fuera de este esquema.
-- En un Postgres normal (PGlite, pruebas) esos roles no existen y el bloque no hace nada.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE format('REVOKE ALL ON SCHEMA %I FROM anon, authenticated', current_schema());
    EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM anon, authenticated', current_schema());
  END IF;
END $$;
